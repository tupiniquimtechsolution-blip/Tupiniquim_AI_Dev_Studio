test('terminal requires confirmation and keeps independent real PTY sessions', async ({ page }) => {
  await enter(page)
  await expect(page.locator('.web-studio')).toHaveAttribute('aria-busy', 'false')
  await page.evaluate(() => {
    const observed = window as Window & { terminalEvidence?: Array<{ terminalId: string; data: string; exited?: boolean }> }
    observed.terminalEvidence = []
    window.studio.terminal.onData((event) => observed.terminalEvidence?.push(event))
  })
  await page.locator('.ws-tools-menu summary').click()
  await page.getByRole('button', { name: 'Terminal', exact: true }).click()
  page.once('dialog', (dialog) => { void dialog.dismiss() })
  await page.getByRole('button', { name: 'Iniciar terminal', exact: true }).click()
  await expect(page.getByText('Terminal parado', { exact: true })).toBeVisible()
  page.once('dialog', (dialog) => { void dialog.accept() })
  await page.getByRole('button', { name: 'Iniciar terminal', exact: true }).click()
  const ids = () => page.evaluate(() => [...new Set((window as Window & { terminalEvidence?: Array<{ terminalId: string }> }).terminalEvidence?.map((event) => event.terminalId))])
  await expect.poll(async () => (await ids()).length).toBe(1)
  const first = (await ids())[0]
  if (first === undefined) throw new Error('No PTY event')
  await page.evaluate((terminalId) => window.studio.terminal.write({ terminalId, data: 'TUPINIQUIM_TEST_SESSION=first\r' }), first)
  await page.getByRole('button', { name: 'Nova sessão', exact: true }).click()
  page.once('dialog', (dialog) => { void dialog.accept() })
  await page.getByRole('button', { name: 'Iniciar terminal', exact: true }).click()
  await expect.poll(async () => (await ids()).length).toBe(2)
  const second = (await ids()).find((id) => id !== first)
  if (second === undefined) throw new Error('No second PTY')
  await page.evaluate((terminalId) => window.studio.terminal.write({ terminalId, data: 'printf "%s" "${TUPINIQUIM_TEST_SESSION-unset}" > terminal-second.txt\r' }), second)
  await expect.poll(async () => page.evaluate(async () => { const result = await window.studio.workspace.read({ relativePath: 'terminal-second.txt' }); return result.ok ? result.value.content : null })).toBe('unset')
  await page.getByRole('button', { name: 'Sessão 1', exact: true }).click()
  await page.evaluate((terminalId) => window.studio.terminal.write({ terminalId, data: 'printf "%s" "$TUPINIQUIM_TEST_SESSION" > terminal-first.txt\r' }), first)
  await expect.poll(async () => page.evaluate(async () => { const result = await window.studio.workspace.read({ relativePath: 'terminal-first.txt' }); return result.ok ? result.value.content : null })).toBe('first')
  await page.getByRole('button', { name: 'Nova sessão', exact: true }).click()
  await page.getByRole('button', { name: 'Nova sessão', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Nova sessão', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Fechar painel', exact: true }).click()
  await expect.poll(async () => page.evaluate(() => {
    const events = (window as Window & { terminalEvidence?: Array<{ terminalId: string; exited?: boolean }> }).terminalEvidence ?? []
    return new Set(events.filter((event) => event.exited).map((event) => event.terminalId)).size
  })).toBe(2)
})

test('gateway rejects competing stale saves and plans without persisted approval', async ({ page }) => {
  await enter(page)
  const outcome = await page.evaluate(async () => {
    const initial = await window.studio.workspace.write({ relativePath: 'cas-hosted.txt', content: 'baseline' })
    if (!initial.ok) throw new Error('Fixture creation failed')
    const competing = await Promise.all(['first', 'second'].map((content) => window.studio.workspace.write({ relativePath: 'cas-hosted.txt', content, expectedHash: initial.value.hash })))
    const unreviewed = await window.studio.workspace.write({ relativePath: 'cas-hosted.txt', content: 'unreviewed replacement' })
    const plan = await window.studio.planning.create({ objective: 'Verificar rejeição de plano sem aprovação', mode: 'PLAN' })
    if (!plan.ok) throw new Error('No plan')
    const weakened = await window.studio.planning.update({ executionId: plan.value.execution.id, plan: { ...plan.value.plan, steps: plan.value.plan.steps.map((step) => ({ ...step, requiresApproval: false })) } })
    const started = await window.studio.planning.start({ executionId: plan.value.execution.id })
    const read = await window.studio.workspace.read({ relativePath: 'cas-hosted.txt' })
    return { successful: competing.filter((result) => result.ok).length, unreviewed: unreviewed.ok, weakened: weakened.ok, started: started.ok, content: read.ok && read.value.content }
  })
  expect(outcome.successful).toBe(1)
  expect(outcome.unreviewed).toBe(false)
  expect(outcome.started).toBe(false)
  expect(outcome.weakened).toBe(false)
  expect(['first', 'second']).toContain(outcome.content)
})

test('manual file creation requires review and never replaces an existing file', async ({ page }) => {
  await enter(page)
  await page.locator('.ws-tools-menu summary').click()
  await page.getByRole('button', { name: 'Arquivos', exact: true }).click()
  await page.getByText('Novo arquivo', { exact: true }).click()
  await page.getByLabel('Caminho do novo arquivo').fill('approved-hosted.txt')
  await page.getByLabel('Conteúdo do novo arquivo').fill('Conteúdo revisado no navegador')
  await page.getByRole('button', { name: 'Preparar revisão', exact: true }).click()
  await expect(page.getByLabel('Conteúdo do novo arquivo')).toHaveAttribute('readonly', '')
  const absent = await page.evaluate(() => window.studio.workspace.read({ relativePath: 'approved-hosted.txt' }))
  expect(absent.ok).toBe(false)
  await page.getByRole('button', { name: 'Aprovar e criar arquivo' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Arquivo criado: approved-hosted.txt' })).toBeVisible()
  const original = await page.evaluate(() => window.studio.workspace.read({ relativePath: 'approved-hosted.txt' }))
  expect(original.ok && original.value.content).toBe('Conteúdo revisado no navegador')
  const denied = await page.evaluate(async () => {
    const prepared = await window.studio.workspace.prepareCreate?.({ relativePath: 'approved-hosted.txt', content: 'tentativa de sobrescrita' })
    if (!prepared?.ok) throw new Error('No review')
    const result = await window.studio.workspace.approveCreate?.({ reviewId: prepared.value.id })
    const bypass = await window.studio.planning.applyWorkspaceWrite({ executionId: crypto.randomUUID(), stepId: crypto.randomUUID(), effectId: crypto.randomUUID(), relativePath: 'approved-hosted.txt', content: 'bypass' })
    const preserved = await window.studio.workspace.read({ relativePath: 'approved-hosted.txt' })
    return { replacement: result?.ok, bypass: bypass.ok, preserved: preserved.ok && preserved.value.content }
  })
  expect(denied).toEqual({ replacement: false, bypass: false, preserved: 'Conteúdo revisado no navegador' })
})

