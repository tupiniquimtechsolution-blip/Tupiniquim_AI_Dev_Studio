import { expect, test, type Page } from '@playwright/test'

const enter = async (page: Page): Promise<void> => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Abrir Studio', exact: true }).first().click()
  await expect(page.locator('.web-studio .brand')).toContainText('Tupiniquim')
  await expect(page.getByRole('heading', { name: 'Em que vamos trabalhar?' })).toBeVisible()
}

test('preferences persist shortcuts and reject invalid profiles on the server', async ({ page }) => {
  await enter(page)
  await page.locator('.ws-tools-menu summary').click()
  await page.getByRole('button', { name: 'Preferências', exact: true }).click()
  await page.getByLabel('Atalho: Atividade').selectOption('Mod+Alt+KeyJ')
  await page.getByLabel('Atalho: Arquivos').selectOption('Mod+Alt+KeyJ')
  await page.getByRole('button', { name: 'Salvar atalhos' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Atalho duplicado.' })).toBeVisible()
  await page.getByLabel('Atalho: Arquivos').selectOption('')
  await page.getByRole('button', { name: 'Salvar atalhos' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Atalhos salvos.' })).toBeVisible()
  await page.reload()
  await expect(page.locator('.web-studio')).toBeVisible()
  await page.locator('.ws-tools-menu summary').focus()
  await page.keyboard.press('Control+Alt+j')
  await expect(page.getByRole('dialog', { name: 'Atividade da sessão' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByLabel('Mensagem ao agente').focus()
  await page.keyboard.press('Control+Alt+j')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const rejected = await page.evaluate(async () => {
    const current = await window.studio.settings.get()
    if (!current.ok) throw new Error('Missing profile')
    const invalid = { ...current.value, theme: { ...current.value.theme, text: current.value.theme.background } }
    const lowContrast = await window.studio.settings.save({ profile: invalid })
    const duplicate = await window.studio.settings.save({ profile: { ...current.value, shortcuts: { files: 'Mod+Alt+KeyF', activity: 'Mod+Alt+KeyF' } } })
    const imported = await window.studio.settings.import({ serialized: JSON.stringify({ ...current.value, density: 'INVALID' }) })
    const preserved = await window.studio.settings.get()
    return { lowContrast: lowContrast.ok, duplicate: duplicate.ok, imported: imported.ok, preserved: preserved.ok && preserved.value.shortcuts?.activity }
  })
  expect(rejected).toEqual({ lowContrast: false, duplicate: false, imported: false, preserved: 'Mod+Alt+KeyJ' })
})

test('HUD has keyboard modals and four responsive layouts', async ({ page }, info) => {
  await enter(page)
  const tools = page.locator('.ws-tools-menu summary')
  await tools.click()
  await page.getByRole('button', { name: 'Atividade', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Fechar painel' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Fechar painel' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(tools).toBeFocused()
  await tools.click()
  await page.getByRole('button', { name: 'Control Center', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Fechar Control Center' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(tools).toBeFocused()
  for (const width of [390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(page.getByLabel('Mensagem ao agente')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
    await page.screenshot({ path: info.outputPath(`hud-${width}.png`) })
  }
})

test('real temporary filesystem supports search, edit, diff and save', async ({ page }) => {
  await enter(page)
  const created = await page.evaluate(() => window.studio.workspace.write({ relativePath: 'hosted-fixture.txt', content: 'hosted baseline\n' }))
  expect(created.ok).toBe(true)
  await page.locator('.ws-tools-menu summary').click()
  await page.getByRole('button', { name: 'Arquivos', exact: true }).click()
  await expect(page.getByLabel('Buscar no conteúdo')).toBeVisible()
  await page.getByLabel('Buscar no conteúdo').fill('hosted baseline')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await page.getByRole('button', { name: /hosted-fixture.txt:1/ }).click()
  await expect(page.locator('.monaco-editor')).toBeVisible()
  // The readonly hidden IME textarea is not the user's editable surface.
  await page.locator('.monaco-editor .view-lines').click()
  await page.keyboard.press('Control+End')
  await page.keyboard.type('edited in hosted browser\n')
  await expect(page.getByRole('button', { name: 'Salvar', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Comparar alterações', exact: true }).click()
  await expect(page.locator('.monaco-diff-editor')).toBeVisible()
  await page.getByRole('button', { name: 'Voltar ao editor', exact: true }).click()
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Arquivo salvo.' })).toBeVisible()
  const read = await page.evaluate(() => window.studio.workspace.read({ relativePath: 'hosted-fixture.txt' }))
  expect(read.ok && read.value.content).toContain('edited in hosted browser')
})

test('Prompt Architect saves versions, validates, compiles, compares and exports', async ({ page }) => {
  await enter(page)
  await page.locator('.ws-tools-menu summary').click()
  await page.getByRole('button', { name: 'Prompt Architect', exact: true }).click()
  const pane = page.getByRole('dialog', { name: 'Prompt Architect', exact: true })
  await pane.getByLabel('Nome do template').fill('Hosted prompt')
  await pane.getByLabel('Conteúdo do template').fill('Objetivo: {{objetivo}}\nRestrições: não sair do escopo.\nAceite: validar.')
  await pane.getByRole('button', { name: 'Salvar nova versão' }).click()
  await expect(pane.getByRole('status')).toContainText('Versão 1 salva')
  await pane.getByRole('button', { name: 'Compilar versão salva' }).click()
  await expect(pane.getByRole('status')).toContainText('obrigatória')
  await pane.getByLabel('Valor de objetivo').fill('Executar no runner')
  await pane.getByRole('button', { name: 'Compilar versão salva' }).click()
  await expect(pane.getByRole('region', { name: 'Resultado do Prompt Architect' })).toContainText('Executar no runner')
  await pane.getByLabel('Conteúdo do template').fill('Objetivo: {{objetivo}}\nRestrições: não sair do escopo.\nAceite: validar.\nVersão adicional.')
  await pane.getByRole('button', { name: 'Salvar nova versão' }).click()
  await expect(pane.getByRole('status')).toContainText('Versão 2 salva')
  await pane.getByLabel('Comparar com').selectOption({ label: 'Hosted prompt · v1' })
  await pane.getByRole('button', { name: 'Comparar versões salvas' }).click()
  await expect(pane.getByRole('region', { name: 'Resultado do Prompt Architect' })).toContainText('Versão adicional.')
  const downloadPromise = page.waitForEvent('download')
  await pane.getByRole('button', { name: 'Exportar versão salva' }).click()
  expect((await downloadPromise).suggestedFilename()).toContain('-v2.md')
  await pane.getByRole('button', { name: 'Validar rascunho' }).click()
  await expect(pane.getByRole('status')).toContainText('Validação do rascunho concluída')
})
